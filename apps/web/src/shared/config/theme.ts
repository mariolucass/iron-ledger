const toCssDeclarations = (variables: Record<string, string>) =>
  Object.entries(variables)
    .map(([key, value]) => `${key.startsWith("--") ? key : key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}:${value}`)
    .join(";");

/** Stylesheet text for the root theme; a stylesheet (not inline style) so data-theme can override it. */
